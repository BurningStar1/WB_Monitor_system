CREATE SCHEMA IF NOT EXISTS stg;

CREATE TABLE IF NOT EXISTS stg.wb_orders (
    srid TEXT PRIMARY KEY,
    date TIMESTAMPTZ,
    last_change_date TIMESTAMPTZ,
    supplier_article TEXT,
    tech_size TEXT,
    barcode TEXT,
    total_price NUMERIC(14, 2),
    discount_percent NUMERIC(6, 2),
    warehouse_name TEXT,
    oblast TEXT,
    income_id BIGINT,
    odid BIGINT,
    nm_id BIGINT,
    subject TEXT,
    category TEXT,
    brand TEXT,
    is_cancel BOOLEAN DEFAULT FALSE,
    cancel_dt TIMESTAMPTZ,
    price_with_disc NUMERIC(14, 2),
    finished_price NUMERIC(14, 2),
    source_loaded_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stg.wb_sales (
    sale_id TEXT PRIMARY KEY,
    date TIMESTAMPTZ,
    last_change_date TIMESTAMPTZ,
    supplier_article TEXT,
    tech_size TEXT,
    barcode TEXT,
    total_price NUMERIC(14, 2),
    discount_percent NUMERIC(6, 2),
    is_supply BOOLEAN DEFAULT FALSE,
    is_realization BOOLEAN DEFAULT FALSE,
    promo_code_discount NUMERIC(14, 2),
    warehouse_name TEXT,
    country_name TEXT,
    oblast_okrug_name TEXT,
    region_name TEXT,
    income_id BIGINT,
    odid BIGINT,
    spp NUMERIC(8, 2),
    for_pay NUMERIC(14, 2),
    finished_price NUMERIC(14, 2),
    price_with_disc NUMERIC(14, 2),
    nm_id BIGINT,
    subject TEXT,
    category TEXT,
    brand TEXT,
    is_storno BOOLEAN DEFAULT FALSE,
    source_loaded_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stg.wb_stocks (
    id BIGSERIAL PRIMARY KEY,
    warehouse_name TEXT,
    supplier_article TEXT,
    nm_id BIGINT,
    barcode TEXT,
    quantity INT,
    in_way_to_client INT,
    in_way_from_client INT,
    quantity_full INT,
    category TEXT,
    subject TEXT,
    brand TEXT,
    tech_size TEXT,
    price NUMERIC(14, 2),
    discount NUMERIC(6, 2),
    is_supply BOOLEAN DEFAULT FALSE,
    is_realization BOOLEAN DEFAULT FALSE,
    source_loaded_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- --- Рекламные кампании (Promotion API) --- --
CREATE TABLE IF NOT EXISTS stg.wb_ads_daily (
    ads_date DATE NOT NULL,
    campaign_id BIGINT NOT NULL,
    nm_id BIGINT NOT NULL DEFAULT 0,
    views INT NOT NULL DEFAULT 0,
    clicks INT NOT NULL DEFAULT 0,
    ctr NUMERIC(8, 4) DEFAULT 0,
    cpc NUMERIC(14, 2) DEFAULT 0,
    spend NUMERIC(14, 2) NOT NULL DEFAULT 0,
    atbs INT NOT NULL DEFAULT 0,
    orders_count INT NOT NULL DEFAULT 0,
    shks INT NOT NULL DEFAULT 0,
    sum_price NUMERIC(14, 2) DEFAULT 0,
    source_loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (ads_date, campaign_id, nm_id)
);
